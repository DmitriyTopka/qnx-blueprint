"""QNX security policies and the architecture contract.

Two directions:

* `generate()` writes the channel rules of a QNX 8.0 security policy from a
  contract: one type per process, `allow_attach` for the names the servers
  register, and one `channel connect` rule per allowed edge. With that policy
  in place the kernel refuses a connection the contract does not allow, so a
  backdoor fails at `name_open()` on the target and not only in CI.

* `compare()` reads an existing policy (the text form, before secpolcompile)
  and reports where it and the contract disagree: connections the policy lets
  through that the contract forbids, and contract edges the policy would block.

The policy language is described in the QNX OS System Security Guide,
"Security policy language". Only the statements that decide channel
connections are interpreted here: type, attribute, `allow ... :channel connect`
and the `channel_connect` ability. Other known statements (allow_attach,
derive_type, ...) are skipped. The parser fails closed: an allow rule or a
statement it cannot read is an error, never silently dropped, because a
dropped rule could hide a connection and turn into a false pass.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import Dict, Iterable, List, Optional, Set, Tuple

from . import checks
from .contract import Contract


class PolicyError(Exception):
    pass


def type_name(process: str) -> str:
    """Default security type for a process: lower case, `_t` suffix."""
    base = re.sub(r"[^A-Za-z0-9_]", "_", process).lower()
    if not base or base[0].isdigit():
        base = "p_" + base
    return base + "_t"


def types_for(contract: Contract, overrides: Optional[Dict[str, str]] = None) -> Dict[str, str]:
    overrides = overrides or {}
    unknown = set(overrides) - set(contract.processes)
    if unknown:
        raise PolicyError(f"--type for {sorted(unknown)[0]}, which is not a process in the contract")
    return {p: overrides.get(p, type_name(p)) for p in contract.processes}


def generate(contract: Contract, attach: Optional[Dict[str, List[str]]] = None,
             overrides: Optional[Dict[str, str]] = None, source: str = "") -> str:
    """Policy text with the types and channel rules the contract implies."""
    types = types_for(contract, overrides)
    attach = attach or {}
    unknown = set(attach) - set(contract.processes)
    if unknown:
        raise PolicyError(f"--attach for {sorted(unknown)[0]}, which is not a process in the contract")
    lines = [
        f"# Channel rules for {contract.system or 'the system'}, generated by blueprint secpol"
        + (f" from {source}" if source else "") + ".",
        "# Only the processes in the contract are covered. Merge this into the policy",
        "# for the whole system (secpolgenerate gives a starting point), compile it",
        "# with secpolcompile and start each process with its type, e.g.",
        f"#   on -T {types[contract.processes[0]]} {contract.processes[0]}",
        "",
    ]
    for p in contract.processes:
        lines.append(f"type {types[p]};")
    lines.append("")
    for p in contract.processes:
        for path in attach.get(p, []):
            lines.append(f"allow_attach {types[p]} {path};")
    if any(attach.values()):
        lines.append("")
    servers: Dict[str, List[str]] = {}
    for client, server in sorted(contract.allow):
        servers.setdefault(client, []).append(server)
    for client in contract.processes:
        for server in servers.get(client, []):
            lines.append(f"# {client} -> {server}")
            lines.append(f"allow {types[client]} {types[server]}:channel connect;")
    return "\n".join(lines) + "\n"


# ---- reading a policy ---------------------------------------------------------

@dataclass
class Policy:
    types: Set[str] = field(default_factory=set)
    attributes: Dict[str, Set[str]] = field(default_factory=dict)   # attribute -> member types
    connect: Set[Tuple[str, str]] = field(default_factory=set)      # (client type, channel type)
    lines: Dict[Tuple[str, str], int] = field(default_factory=dict)  # rule -> line number


_SET = r"(\{[^}]*\}|[A-Za-z0-9_]+)"
# allow SUBJECTS OBJECTS:CLASSES PERMISSIONS   (after spaces around ':' and ',' are removed)
_ALLOW = re.compile(rf"^allow\s+{_SET}\s+{_SET}:{_SET}\s+(\{{.*\}}|\S+)$", re.S)
_TYPE_NAME = re.compile(r"^[A-Za-z0-9_]+$")
# An ability, optionally with a range: spawn, network/bind/privport, mem_phys:0x1000-0x2000,
# channel_connect:a_t,b_t. Anything else (*, ~, stray punctuation) is not understood.
_ABILITY_TOKEN = re.compile(r"^[A-Za-z0-9_/]+(:[A-Za-z0-9_,\-]+)?$")
ALL_TYPES = "*"
# Statement keywords of the policy language that do not decide channel connections.
OTHER_STATEMENTS = {"allow_attach", "allow_link", "derive_type", "default_spawn_type", "range",
                    "ability", "class", "mount_point", "gain_priv"}


def _names(token: str, commas: bool = True) -> List[str]:
    """Members of a `{ ... }` set (or the single name). Type and class sets may
    use commas or spaces; ability blocks keep commas, they belong to ranges."""
    token = token.strip()
    if token.startswith("{"):
        token = token[1:-1]
    return [t for t in re.split(r"[\s,]+" if commas else r"\s+", token) if t]


def _plain(number: int, names: List[str], what: str) -> List[str]:
    for n in names:
        if not _TYPE_NAME.match(n):
            raise PolicyError(f"line {number}: cannot read {what} {n!r}")
    return names


def _statements(text: str) -> Iterable[Tuple[int, str]]:
    """(line number, statement) with comments removed, split at ';'."""
    buf, start = [], None
    for number, raw in enumerate(text.splitlines(), 1):
        line = raw.split("#", 1)[0]
        while ";" in line:
            head, line = line.split(";", 1)
            buf.append(head)
            stmt = " ".join(" ".join(buf).split())
            if stmt:
                yield (start or number, stmt)
            buf, start = [], None
        if line.strip():
            if start is None:
                start = number
            buf.append(line)
    if " ".join(buf).strip():
        raise PolicyError(f"line {start}: statement does not end with ';'")


def _connect_targets(number: int, permissions: str) -> List[str]:
    """Types an ability block lets the subject connect to (ALL_TYPES for a
    bare channel_connect without a range)."""
    targets: List[str] = []
    for item in _names(permissions, commas=False):
        if not _ABILITY_TOKEN.match(item):
            raise PolicyError(f"line {number}: cannot read ability {item!r}")
        if item == "channel_connect":
            targets.append(ALL_TYPES)
        elif item.startswith("channel_connect:"):
            names = [t for t in item.split(":", 1)[1].split(",")]
            if not names or not all(_TYPE_NAME.match(t) for t in names):
                raise PolicyError(f"line {number}: cannot read the range of {item!r}")
            targets += names
    return targets


def parse(text: str) -> Policy:
    """Read the statements that decide channel connections.

    Fails closed: an allow statement that mentions channels and is not in a
    form this parser understands is an error, so a rule can never be skipped
    and turn into a false pass.
    """
    pol = Policy()
    pending: List[Tuple[int, List[str], List[str]]] = []   # resolved after all types are known
    for number, stmt in _statements(text):
        word = stmt.split(None, 1)[0]
        if word == "type":
            parts = [p.strip() for p in stmt[4:].split(",")]
            name = parts[0]
            pol.types.add(name)
            for attr in parts[1:]:
                pol.attributes.setdefault(attr, set()).add(name)
        elif word == "attribute":
            pol.attributes.setdefault(stmt.split()[1], set())
        elif word == "allow":
            flat = re.sub(r"\s*([:,])\s*", r"\1", stmt)
            m = _ALLOW.match(flat)
            if m is None:
                raise PolicyError(f"line {number}: cannot read this rule: {stmt[:120]}")
            subjects = _plain(number, _names(m.group(1)), "type")
            objects = _plain(number, _names(m.group(2)), "type")
            classes, permissions = _plain(number, _names(m.group(3)), "class"), m.group(4)
            if "channel" in classes:
                perms = _plain(number, _names(permissions), "channel permission")
                if "connect" in perms:
                    pending.append((number, subjects, objects))
            if "ability" in classes:
                # An ability always belongs to the subject, whatever the object.
                targets = _connect_targets(number, permissions)
                if targets:
                    pending.append((number, subjects, targets))
            elif "channel_connect" in permissions:
                raise PolicyError(f"line {number}: channel_connect outside an ability rule: {stmt[:120]}")
        elif word not in OTHER_STATEMENTS:
            raise PolicyError(f"line {number}: unknown statement: {stmt[:120]}")
    with_rules = {s for _n, subjects, _o in pending for s in subjects}
    known = pol.types | set(pol.attributes) | {"self", "default_rules", ALL_TYPES}
    for number, subjects, objects in pending:
        # secpolcompile rejects undeclared names too; here it also catches an
        # ability keyword swallowed into a range ("channel_connect:a_t,channel_connect").
        for name in subjects + objects:
            if name not in known:
                raise PolicyError(f"line {number}: {name!r} is not a declared type or attribute")
        for s in _expand(pol, subjects, with_rules):
            if objects == ["self"]:
                targets = [s]
            elif ALL_TYPES in objects:
                targets = sorted(pol.types)
            else:
                targets = _expand(pol, objects, with_rules)
            for o in targets:
                pol.connect.add((s, o))
                pol.lines.setdefault((s, o), number)
    return pol


def _expand(pol: Policy, names: List[str], with_rules: Set[str] = frozenset()) -> List[str]:
    out: List[str] = []
    for n in names:
        if n == "default_rules":
            # Granted to every type that has an allow rule of its own; taking
            # all types errs towards reporting more connections, not fewer.
            out += sorted(pol.types - {"default_rules"})
        elif n in pol.attributes:
            out += sorted(pol.attributes[n])
        elif n != "self":
            out.append(n)
    return out


# ---- comparing ------------------------------------------------------------------

def compare(contract: Contract, policy: Policy, path: str = "policy",
            overrides: Optional[Dict[str, str]] = None) -> List[checks.Finding]:
    types = types_for(contract, overrides)
    by_type = {t: p for p, t in types.items()}
    out: List[checks.Finding] = []
    missing = [p for p in contract.processes if types[p] not in policy.types]
    if missing:
        out.append(checks.Finding(
            "secpol", checks.WARNING,
            f"{path} has no type for {', '.join(missing)}",
            f"Expected {', '.join(types[p] for p in missing)}. Those processes would run as whatever "
            f"type started them, so the channel rules below cannot apply to them. Pass --type "
            f"process=type if the policy uses other names.",
            missing))
    for client, server in sorted(contract.allow):
        if (types[client], types[server]) not in policy.connect:
            out.append(checks.Finding(
                "secpol", checks.ERROR,
                f"policy blocks {client} -> {server}, which the contract allows",
                f"No rule in {path} lets {types[client]} connect to a channel of type {types[server]}. "
                f"With the policy enforced the kernel refuses {client}'s name_open() or ConnectAttach() to {server} with EPERM. "
                f"Add: allow {types[client]} {types[server]}:channel connect;",
                [client, server], [], {"client_type": types[client], "server_type": types[server]}))
    for (ct, st), line in sorted(policy.lines.items()):
        client, server = by_type.get(ct), by_type.get(st)
        if client is None or server is None or client == server or (client, server) in contract.allow:
            continue
        out.append(checks.Finding(
            "secpol", checks.ERROR,
            f"policy lets {client} connect to {server}, which the contract forbids",
            f"{path} line {line} allows {ct} to connect to {st}. The kernel will not stop this "
            f"path, so a build that adds it only shows up in a trace. Remove the rule, or add "
            f"'{client} -> {server}' to the contract if the design changed.",
            [client, server], [], {"line": line, "client_type": ct, "server_type": st}))
    return out


def parse_pairs(items: List[str], what: str) -> Dict[str, List[str]]:
    """NAME=VALUE options, repeatable."""
    out: Dict[str, List[str]] = {}
    for item in items:
        name, sep, value = item.partition("=")
        if not sep or not name or not value:
            raise PolicyError(f"--{what} wants PROCESS=VALUE, got {item!r}")
        out.setdefault(name, []).append(value)
    return out
