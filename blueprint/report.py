"""Single-file HTML report: verdict, architecture graph, findings, edge table.

No external assets, so the file can be attached to a CI run and opened offline.
"""

from __future__ import annotations

import html
import math
import statistics
from typing import Dict, List, Optional, Tuple

from . import checks, contract as contract_mod, ipc, kev, topology


def render(trace: kev.Trace, model: ipc.IpcModel, con: contract_mod.Contract,
           findings: List[checks.Finding], topo: topology.Topology, trace_path: str,
           explanations: Optional[Dict[int, "object"]] = None) -> str:
    errors = [f for f in findings if f.severity == checks.ERROR]
    passed = not errors
    duration = 0.0
    if trace.events:
        duration = trace.seconds(trace.events[-1].t_cycles - trace.events[0].t_cycles)
    a = trace.attributes
    latencies = _latencies(trace, model, con)

    parts = [
        "<!doctype html><html lang=en><head><meta charset=utf-8>",
        "<meta name=viewport content='width=device-width,initial-scale=1'>",
        f"<title>Blueprint: {_e(con.system or 'system')} {'pass' if passed else 'fail'}</title>",
        f"<style>{CSS}</style></head><body><main>",
        "<header>",
        f"<div class='verdict {'pass' if passed else 'fail'}'>{'PASS' if passed else 'FAIL'}</div>",
        "<div class=headtext>",
        f"<h1>{_e(con.system or 'System')} architecture check</h1>",
        f"<p class=sub>{len(errors)} errors, {len(findings) - len(errors)} warnings. "
        f"Trace {_e(trace_path)}: QNX {_e(a.get('SYS_RELEASE', '?'))} on {_e(a.get('MACHINE', '?'))}, "
        f"{trace.cpu_count} CPUs, {duration:.2f} s, {len(trace.events):,} events.</p>",
        "</div></header>",
        "<section class=grid>",
        f"<div class=card><h2>Architecture</h2>{_graph(con, topo, findings)}{LEGEND}</div>",
        f"<div class=card><h2>Findings</h2>{_findings(findings, explanations or {})}</div>",
        "</section>",
        f"<section class=card><h2>Message traffic</h2>{_edge_table(con, topo, latencies)}</section>",
        "<footer>Generated by qnx-blueprint. Times come from the trace clock; on an emulated "
        "target they are inflated. Open the Perfetto export at ui.perfetto.dev to see every "
        "message as an arrow between threads.</footer>",
        "</main></body></html>",
    ]
    return "".join(parts)


def _e(text: object) -> str:
    return html.escape(str(text), quote=True)


def _latencies(trace: kev.Trace, model: ipc.IpcModel,
               con: contract_mod.Contract) -> Dict[Tuple[str, str], List[float]]:
    out: Dict[Tuple[str, str], List[float]] = {}
    for tx in model.transactions:
        if tx.t_reply is None or tx.status != "replied":
            continue
        key = (model.name(tx.client_pid), model.name(tx.server_pid))
        if key[0] in con.processes and key[1] in con.processes:
            out.setdefault(key, []).append((tx.t_reply - tx.t_send) / trace.cycles_per_sec * 1000)
    return out


def _graph(con: contract_mod.Contract, topo: topology.Topology, findings: List[checks.Finding]) -> str:
    names = list(con.processes)
    w, h, r = 520, 360, 130
    cx, cy = w / 2, h / 2
    pos = {}
    for i, name in enumerate(names):
        angle = -math.pi / 2 + 2 * math.pi * i / len(names)
        pos[name] = (cx + r * 1.45 * math.cos(angle), cy + r * math.sin(angle))

    bad_edges = {(f.processes[0], f.processes[1]) for f in findings
                 if f.check == "unexpected-edge" and len(f.processes) >= 2}
    cycle_edges = set()
    for f in findings:
        if f.check == "wait-cycle":
            cyc = f.data.get("cycle", [])
            cycle_edges |= {(cyc[i], cyc[(i + 1) % len(cyc)]) for i in range(len(cyc))}
    hurt = {p for f in findings if f.severity == checks.ERROR for p in f.processes}

    svg = [f"<svg viewBox='0 0 {w} {h}' role=img aria-label='message graph'>",
           "<defs>",
           "<marker id=ah viewBox='0 0 10 10' refX=9 refY=5 markerWidth=7 markerHeight=7 orient=auto-start-reverse>"
           "<path d='M0,0 L10,5 L0,10 z' fill=context-stroke /></marker>",
           "</defs>"]
    edges = set(topo.edges) | set(con.allow)
    for client, server in sorted(edges):
        if client not in pos or server not in pos:
            continue
        x1, y1 = pos[client]
        x2, y2 = pos[server]
        dx, dy = x2 - x1, y2 - y1
        d = math.hypot(dx, dy) or 1
        # Shorten to the node radius and bend a little so a->b and b->a do not overlap.
        sx, sy = x1 + dx / d * 30, y1 + dy / d * 30
        ex, ey = x2 - dx / d * 32, y2 - dy / d * 32
        mx, my = (sx + ex) / 2 - dy / d * 18, (sy + ey) / 2 + dx / d * 18
        if (client, server) in cycle_edges:
            cls = "edge cycle"
        elif (client, server) in bad_edges:
            cls = "edge bad"
        elif (client, server) in topo.edges:
            cls = "edge ok"
        else:
            cls = "edge unused"
        msgs = topo.edges[(client, server)].messages if (client, server) in topo.edges else 0
        svg.append(f"<path class='{cls}' d='M{sx:.1f},{sy:.1f} Q{mx:.1f},{my:.1f} {ex:.1f},{ey:.1f}' "
                   f"marker-end='url(#ah)'><title>{_e(client)} to {_e(server)}: {msgs} messages</title></path>")
    for name, (x, y) in pos.items():
        cls = "node hurt" if name in hurt else "node"
        svg.append(f"<g class='{cls}'><circle cx={x:.1f} cy={y:.1f} r=28 />"
                   f"<text x={x:.1f} y={y + 4:.1f} text-anchor=middle>{_e(name)}</text></g>")
    svg.append("</svg>")
    return "".join(svg)


def _findings(findings: List[checks.Finding], explanations: Dict[int, object]) -> str:
    if not findings:
        return "<p class=empty>The trace matches the contract.</p>"
    items = []
    order = sorted(enumerate(findings), key=lambda p: (p[1].severity != checks.ERROR, p[1].check))
    for i, f in order:
        ev = ", ".join(str(e) for e in f.events) or "none"
        items.append(
            f"<article class='finding {f.severity}'>"
            f"<div class=fhead><span class=tag>{_e(f.severity)}</span><code>{_e(f.check)}</code></div>"
            f"<h3>{_e(f.title)}</h3><p>{_e(f.detail)}</p>"
            f"<p class=evidence>Evidence: trace events {_e(ev)}</p>"
            + (_explanation(explanations[i]) if i in explanations else "")
            + "</article>")
    return "".join(items)


def _explanation(e) -> str:
    refs = " ".join(f"<a href='{_e(url)}'>{_e(name)}</a>" for name, url in e.doc_refs.items())
    note = "" if e.verified else "<p class=unverified>Unverified: the explanation cited no trace events.</p>"
    return (
        "<div class=explain>"
        f"<div class=xhead>Why, according to {_e(e.model)} "
        f"<span class=conf>confidence {_e(e.confidence)}</span></div>"
        f"<p>{_e(e.cause)}</p>"
        f"<p><b>At fault:</b> {_e(e.qnx_call)}</p>"
        f"<p><b>Fix:</b> {_e(e.fix_summary)}</p>"
        + (f"<details><summary>Proposed patch</summary><pre>{_e(e.fix_patch)}</pre></details>"
           if e.fix_patch.strip() else "")
        + f"<p class=evidence>Cites events {_e(', '.join(map(str, e.evidence_event_ids)))}"
        + (f" &middot; Docs: {refs}" if refs else "") + "</p>"
        + note + "</div>")


def _edge_table(con: contract_mod.Contract, topo: topology.Topology,
                latencies: Dict[Tuple[str, str], List[float]]) -> str:
    rows = ["<table><thead><tr><th>Client</th><th>Server</th><th>In contract</th><th>Messages</th>"
            "<th>Replied</th><th>Errors</th><th>Unanswered</th><th>Median reply</th><th>Worst reply</th>"
            "<th>Budget</th></tr></thead><tbody>"]
    for (client, server), e in sorted(topo.edges.items()):
        lat = latencies.get((client, server), [])
        med = f"{statistics.median(lat):.2f} ms" if lat else "-"
        worst = f"{max(lat):.2f} ms" if lat else "-"
        budget = con.budget_for(server)
        over = budget is not None and lat and max(lat) > budget
        allowed = (client, server) in con.allow
        rows.append(
            f"<tr><td>{_e(client)}</td><td>{_e(server)}</td>"
            f"<td class='{'' if allowed else 'bad'}'>{'yes' if allowed else 'no'}</td>"
            f"<td>{e.messages}</td><td>{e.replied}</td><td>{e.errors}</td>"
            f"<td class='{'bad' if e.open else ''}'>{e.open}</td><td>{med}</td>"
            f"<td class='{'bad' if over else ''}'>{worst}</td>"
            f"<td>{f'{budget:g} ms' if budget is not None else '-'}</td></tr>")
    rows.append("</tbody></table>")
    return "<div class=tablewrap>" + "".join(rows) + "</div>"


LEGEND = ("<ul class=legend><li><i class='l ok'></i>allowed, used</li>"
          "<li><i class='l unused'></i>allowed, not seen</li>"
          "<li><i class='l bad'></i>not in contract</li>"
          "<li><i class='l cycle'></i>deadlock loop</li></ul>")

